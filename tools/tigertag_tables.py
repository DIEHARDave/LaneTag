# Writes src/tigertag_db.h from TigerTag's ID tables (the offline copies in
# FF_NFC: python/ffnfc/decoders/data/tigertag).
#
#   python tools/tigertag_tables.py ../FF_NFC/python/ffnfc/decoders/data/tigertag
import json
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(HERE, "..", "src", "tigertag_db.h")


def load(folder, name):
    with open(os.path.join(folder, "id_%s.json" % name), encoding="utf-8") as handle:
        return sorted((e for e in json.load(handle) if "id" in e), key=lambda e: int(e["id"]))


def c(text):
    return json.dumps(text or "", ensure_ascii=True)


def main(folder):
    lines = [
        "// Generated by tools/tigertag_tables.py from TigerTag's ID tables",
        "// (https://tigertag.io, offline copies in FF_NFC). Do not edit.",
        "#pragma once",
        "",
        "#include <stdint.h>",
        "",
        "struct TigerTagMaterial { uint16_t id; const char *material; uint8_t bed; };",
        "struct TigerTagName { uint16_t id; const char *name; };",
        "",
        "// Sorted by id.",
        "static const TigerTagMaterial TIGERTAG_MATERIALS[] = {",
    ]
    for e in load(folder, "material"):
        material = e.get("material_type") or e.get("label") or "PLA"
        if e.get("filled_type"):
            material = "%s-%s" % (material, e["filled_type"])
        bed = int((e.get("recommended") or {}).get("bedTempMax") or 0)
        lines.append("    {%d, %s, %d}," % (int(e["id"]), c(material), min(bed, 255)))
    lines += ["};", "", "static const TigerTagName TIGERTAG_BRANDS[] = {"]
    for e in load(folder, "brand"):
        lines.append("    {%d, %s}," % (int(e["id"]), c(e.get("name"))))
    lines += ["};", "", "static const TigerTagName TIGERTAG_ASPECTS[] = {"]
    for e in load(folder, "aspect"):
        lines.append("    {%d, %s}," % (int(e["id"]), c(e.get("label"))))
    lines += ["};", "", "static const TigerTagName TIGERTAG_DIAMETERS[] = {"]
    for e in load(folder, "diameter"):
        lines.append("    {%d, %s}," % (int(e["id"]), c(e.get("label"))))
    lines += ["};", ""]
    with open(OUT, "w", encoding="utf-8", newline="\n") as handle:
        handle.write("\n".join(lines))
    print("wrote", os.path.normpath(OUT))


if __name__ == "__main__":
    if len(sys.argv) != 2:
        sys.exit(__doc__ if __doc__ else "usage: tigertag_tables.py <tigertag data folder>")
    main(sys.argv[1])
