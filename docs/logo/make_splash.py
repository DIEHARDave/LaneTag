"""Generate the boot logo of the TFT screens (src/splash_logo.h).

Usage: python make_splash.py [CHROME_EXE]
Renders lanetag-logo-dark.svg with headless Chrome at twice the size,
scales it to 300x118 on the screens' background color and stores it as a
64-color PNG (lanetag-splash.png, and its bytes in src/splash_logo.h).
"""
import os, subprocess, sys, tempfile
from PIL import Image

HERE = os.path.dirname(os.path.abspath(__file__))
CHROME = sys.argv[1] if len(sys.argv) > 1 else r"C:\Program Files\Google\Chrome\Application\chrome.exe"
BG = "#101418"          # tft.cpp BG
W, H = 300, 118         # fits the 320x172 and 320x240 screens

with tempfile.TemporaryDirectory() as tmp:
    page = os.path.join(tmp, "splash.html")
    shot = os.path.join(tmp, "splash.png")
    svg = os.path.join(HERE, "lanetag-logo-dark.svg").replace("\\", "/")
    with open(page, "w") as f:
        f.write(f'<!doctype html><body style="margin:0;background:{BG};overflow:hidden">'
                f'<img src="file:///{svg}" style="display:block;width:{W * 2}px"></body>')
    subprocess.run([CHROME, "--headless=new", "--disable-gpu", "--hide-scrollbars",
                    "--force-device-scale-factor=1", f"--window-size={W * 2},{H * 2}",
                    f"--screenshot={shot}", "file:///" + page.replace("\\", "/")],
                   check=True, capture_output=True)
    im = Image.open(shot).convert("RGB").crop((0, 0, W * 2, H * 2)).resize((W, H), Image.LANCZOS)

png = os.path.join(HERE, "lanetag-splash.png")
im.quantize(colors=64, method=Image.Quantize.MEDIANCUT, dither=Image.Dither.NONE).save(png, optimize=True)
data = open(png, "rb").read()

rows = [", ".join(f"0x{b:02x}" for b in data[i:i + 16]) for i in range(0, len(data), 16)]
with open(os.path.join(HERE, "..", "..", "src", "splash_logo.h"), "w", newline="\n") as f:
    f.write("// The full LaneTag logo shown on the TFT screens at start-up: a\n"
            f"// {W}x{H} PNG on the screens' background color. Generated by\n"
            "// docs/logo/make_splash.py from lanetag-logo-dark.svg.\n"
            "#pragma once\n\n#include <pgmspace.h>\n\n"
            f"constexpr int SPLASH_LOGO_W = {W}, SPLASH_LOGO_H = {H};\n"
            "const uint8_t SPLASH_LOGO_PNG[] PROGMEM = {\n    "
            + ",\n    ".join(rows) + "\n};\n")
print(f"{png}: {len(data)} bytes")
